const arRules = new Intl.PluralRules('ar');
export function arCount(n, { one, two, few, many, other }) {
  const form = arRules.select(n);
  if (form === 'one') return one;
  if (form === 'two') return two;
  if (form === 'few') return `${n} ${few}`;
  if (form === 'many') return `${n} ${many}`;
  return `${n} ${other}`;
}
